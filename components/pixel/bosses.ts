// gordo y fuerte, el de ataque doble lleva dos espadas, etc. Generadas con primitivas
// y revisadas a mano; '.' es transparente.

export interface BossSprite { body: Sprite; seal: Sprite }

const layer = (rows: string[], keep: string): Sprite => ({ rows: rows.map(r => r.replace(new RegExp(`[^${keep}]`, 'g'), '.').replace(new RegExp(keep, 'g'), 'o')) });
const boss = (rows: string[]): BossSprite => ({ body: layer(rows, 'o'), seal: layer(rows, 'g') });

